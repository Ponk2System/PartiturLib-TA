-- Global download counter. It is incremented through the RPC below so
-- simultaneous download requests never overwrite each other.
ALTER TABLE public.scores ADD COLUMN IF NOT EXISTS download_count BIGINT NOT NULL DEFAULT 0;

CREATE OR REPLACE FUNCTION public.increment_score_download(score_id BIGINT)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  next_count BIGINT;
BEGIN
  UPDATE public.scores
  SET download_count = download_count + 1
  WHERE id = score_id
  RETURNING download_count INTO next_count;

  IF next_count IS NULL THEN
    RAISE EXCEPTION 'Score not found';
  END IF;

  RETURN next_count;
END;
$$;

GRANT EXECUTE ON FUNCTION public.increment_score_download(BIGINT) TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, username)
  VALUES (NEW.id, COALESCE(NULLIF(NEW.raw_user_meta_data->>'username', ''), split_part(NEW.email, '@', 1), 'Musisi'))
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

CREATE OR REPLACE FUNCTION public.lock_profile_role()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    NEW.id := OLD.id;
    NEW.role := OLD.role;
  END IF;
  NEW.updated_at := NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS lock_profile_role_trigger ON public.profiles;
CREATE TRIGGER lock_profile_role_trigger
  BEFORE UPDATE ON public.profiles FOR EACH ROW EXECUTE PROCEDURE public.lock_profile_role();

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin') $$;

CREATE OR REPLACE FUNCTION public.set_score_uploader()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.uploader_id := auth.uid();
    SELECT username INTO NEW.uploader_name FROM public.profiles WHERE id = auth.uid();
    NEW.uploader_name := COALESCE(NEW.uploader_name, 'Musisi');
  ELSE
    NEW.uploader_id := OLD.uploader_id;
    NEW.uploader_name := OLD.uploader_name;
  END IF;
  NEW.updated_at := NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS set_score_uploader_trigger ON public.scores;
CREATE TRIGGER set_score_uploader_trigger
  BEFORE INSERT OR UPDATE ON public.scores FOR EACH ROW EXECUTE PROCEDURE public.set_score_uploader();

