-- 1. Create SCORES table (Partitur Musik)
CREATE TABLE IF NOT EXISTS public.scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,                                     -- Judul karya musik / partitur
    composer TEXT NOT NULL,                                  -- Pencipta / Komposer asli
    arranger TEXT DEFAULT 'Original',                        -- Pengaransemen / Arranger
    year_composed INTEGER,                                   -- Tahun diciptakan (misal: 1808)
    category TEXT NOT NULL DEFAULT 'Orchestra',              -- 'Orchestra', 'String Section', 'Solo Instrument', 'Woodwind & Brass', 'Choir / Vocal'
    instrumentation TEXT[] DEFAULT '{}',                     -- Daftar instrumen / partitur bagian (Violin I, Cello, Flute, dll.)
    difficulty TEXT DEFAULT 'Intermediate',                  -- 'Beginner', 'Easy', 'Intermediate', 'Advanced', 'Professional'
    key_signature TEXT DEFAULT 'C Major',                    -- Nada dasar (misal: C Minor, G Major)
    tempo TEXT DEFAULT 'Allegro',                            -- Indikasi tempo (misal: Allegro, Andante, Presto)
    time_signature TEXT DEFAULT '4/4',                       -- Tanda birama (misal: 4/4, 3/4, 6/8)
    file_url TEXT NOT NULL,                                  -- Link / URL file PDF partitur
    file_name TEXT,                                          -- Nama file PDF asli (misal: 'beethoven_symphony_5.pdf')
    file_size TEXT DEFAULT '1.2 MB',                         -- Ukuran file PDF
    cover_image_url TEXT DEFAULT '/scores/cover-default.svg', -- Cover / thumbnail halaman depan partitur
    description TEXT DEFAULT '',                             -- Deskripsi karya, panduan dinamika, atau catatan sejarah
    movements TEXT[] DEFAULT '{}',                           -- Daftar babak / bagian gerakan (movements)
    duration TEXT DEFAULT '05:00',                           -- Perkiraan durasi (menit:detik)
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create FAVORITES table (Koleksi / Repertoar Favorit Musisi)
CREATE TABLE IF NOT EXISTS public.favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    score_id BIGINT NOT NULL REFERENCES public.scores(id) ON DELETE CASCADE,
    product_id BIGINT GENERATED ALWAYS AS (score_id) STORED, -- Kolom alias kompatibilitas
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_user_score_favorite UNIQUE (user_id, score_id)
);

-- 3. Create REVIEWS / ANNOTATIONS table (Ulasan & Catatan Latihan Partitur)
CREATE TABLE IF NOT EXISTS public.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_id BIGINT NOT NULL REFERENCES public.scores(id) ON DELETE CASCADE,
    product_id BIGINT GENERATED ALWAYS AS (score_id) STORED, -- Kolom alias kompatibilitas
    user_id TEXT NOT NULL,
    rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
    comment TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

